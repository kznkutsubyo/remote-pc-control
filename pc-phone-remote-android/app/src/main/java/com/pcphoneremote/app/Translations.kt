    fun tr(lang: String, key: String): String {
        return when (lang) {
            "ru" -> RU[key] ?: CompanionStrings.get("ru", key) ?: EN[key] ?: key
            "uk" -> UK[key] ?: CompanionStrings.get("uk", key) ?: RU[key] ?: EN[key] ?: key
            "en" -> EN[key] ?: CompanionStrings.get("en", key) ?: key
            else -> CompanionStrings.get(lang, key) ?: EN[key] ?: key
        }
    }

    fun currentLang(context: Context): String {
        return context.applicationContext
            .getSharedPreferences("pc_remote_settings", Context.MODE_PRIVATE)
            .getString("lang", "ru") ?: "ru"
    }

    fun tr(context: Context, key: String): String = tr(currentLang(context), key)
